#include <iostream>

// Демонстрація інкапсуляції в C++: private поля та безпечні public методи
class Hero {
private:
    int hp; // Закрито від прямого доступу: захист від некоректних даних та багів

public:
    // Сеттер: контролює зміну здоров'я
    void setHp(int value) {
        if (value < 0) {
            hp = 0; // Захист: якщо прийшов мінус, фіксуємо 0 (персонаж загинув)
        } else {
            hp = value;
        }
    }

    // Геттер: безпечно повертає поточне значення
    int getHp() {
        return hp;
    }
};

int main() {
    Hero h;

    // Встановлюємо коректне значення
    h.setHp(100);
    std::cout << "Початкове HP: " << h.getHp() << '\n';

    // Спроба встановити недопустиме від'ємне значення
    h.setHp(-50);
    std::cout << "HP після спрацювання захисту: " << h.getHp() << '\n';

    // Спроба прямого доступу:
    // h.hp = 500; // ❌ Помилка компіляції! Член 'Hero::hp' недоступний, бо він private

    return 0;
}
