#include <iostream>

int main() {
    int arr[5] = { 10, 20, 30, 40, 50 };

    // Имя массива arr само по себе является адресом его первого элемента (&arr[0])
    int* ptr = arr;

    for (int i = 0; i < 5; i++) {
        // Доступ через индекс массива и через арифметику указателей дают одинаковый результат
        std::cout << "arr[" << i << "] = " << arr[i] 
                  << " | *(ptr + " << i << ") = " << *(ptr + i) << '\n';
    }

    return 0;
}
