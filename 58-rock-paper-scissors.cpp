#include <iostream>
#include <cstdlib>  // rand(), srand()
#include <ctime>    // time()

int main() {
    // Инициализация генератора случайных чисел (делается ОДИН РАЗ в начале)
    srand(time(nullptr));

    int playerScore = 0;  // Счёт игрока
    int botScore    = 0;  // Счёт бота
    int choice      = 0;  // Выбор игрока

    while (true) {
        // ╔══════════════════════════════╗
        // ║          МЕНЮ ИГРЫ           ║
        // ╚══════════════════════════════╝
        std::cout << "\n=== КАМЕНЬ, НОЖНИЦЫ, БУМАГА ===\n"
                  << "1. Камень\n"
                  << "2. Бумага\n"
                  << "3. Ножницы\n"
                  << "0. Выход\n"
                  << "Ваш выбор: ";
        std::cin >> choice;

        // ─── Выход из игры ───────────────────────────────────────────────
        if (choice == 0) {
            std::cout << "\n=== ИГРА ЗАВЕРШЕНА ===\n"
                      << "Финальный счёт:\n"
                      << "  Игрок : " << playerScore << '\n'
                      << "  Бот   : " << botScore    << '\n';

            if (playerScore > botScore)
                std::cout << "Ты победил в этой серии! Молодец!\n";
            else if (botScore > playerScore)
                std::cout << "Бот победил в этой серии. Попробуй ещё раз!\n";
            else
                std::cout << "Серия закончилась вничью!\n";

            return 0;
        }

        // ─── Проверка корректности ввода ──────────────────────────────────
        if (choice < 1 || choice > 3) {
            std::cout << "Нет такого пункта! Введи 1, 2, 3 или 0.\n";
            continue; // пропускаем этот раунд и идём на следующую итерацию цикла
        }

        // ─── Ход бота: случайное число от 1 до 3 ─────────────────────────
        int botChoice = rand() % 3 + 1;

        // Выводим, что выбрал бот (для наглядности)
        std::string botName;
        if (botChoice == 1) botName = "Камень";
        else if (botChoice == 2) botName = "Бумага";
        else botName = "Ножницы";

        std::cout << "Бот выбрал: " << botName << '\n';

        // ─── Определение победителя в раунде ─────────────────────────────
        if (choice == botChoice) {
            // Оба выбрали одно и то же → ничья
            std::cout << "Ничья! Оба выбрали одно и то же.\n";
        }
        else if ((choice == 1 && botChoice == 3) ||   // Камень бьёт Ножницы
                 (choice == 2 && botChoice == 1) ||   // Бумага  бьёт Камень
                 (choice == 3 && botChoice == 2)) {   // Ножницы бьют Бумагу
            std::cout << "Ты выиграл этот раунд!\n";
            playerScore++;
        }
        else {
            // Во всех остальных комбинациях побеждает бот
            std::cout << "Бот выиграл этот раунд!\n";
            botScore++;
        }

        // ─── Текущий счёт после каждого раунда ───────────────────────────
        std::cout << "Счёт -> Игрок: " << playerScore
                  << " | Бот: "        << botScore << '\n';
    }

    return 0;
}
